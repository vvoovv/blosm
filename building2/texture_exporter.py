import os
import tempfile
import shutil
import bpy
from ..util.blender import loadSceneFromFile
from ..util.blender_extra.material import setImage
from ..progressive.ownership import Ownership, TRANSIENT


_exportTemplateFilename = "building_material_templates.blend"

_renderFileFormats = {
    ".png": "PNG",
    ".jpg": "JPEG",
    ".jpeg": "JPEG"   
}


class TextureExporter:
    
    def __init__(self, assetsDir, assetPackageDir):
        self.assetPackageDir = assetPackageDir
        self.exportTemplateFilename = os.path.join(assetsDir, _exportTemplateFilename)
        # a directory where textures generated by the Compositor File Output node are placed
        self.tmpTextureDir = None
        # Linked template scenes from <_exportTemplateFilename>. They will be unlinked in <self.cleanup(..)>
        self.linkedScenes = []
        self.bakeQueue = None
        self.templateScenes = {}
        self.transient = Ownership()
    
    def cleanup(self):
        if self.bakeQueue:
            self.bakeQueue.close()
            self.bakeQueue = None
        tmpTextureDir = self.tmpTextureDir
        if tmpTextureDir:
            if os.path.basename(tmpTextureDir).startswith('.blosm-textures-'):
                shutil.rmtree(tmpTextureDir)
            self.tmpTextureDir = None
        self.transient.rollback()
        self.templateScenes.clear()
    
    def verifyPath(self, textureDir):
        if not os.path.exists(textureDir):
            os.makedirs(textureDir)
    
    def setTmpTextureDir(self, textureDir):
        if not self.tmpTextureDir:
            self.tmpTextureDir = tempfile.mkdtemp(prefix='.blosm-textures-', dir=textureDir)

    def makeCommonPreparations(self, scene, textureFilename, textureDir):
        self.verifyPath(textureDir)
        self.setTmpTextureDir(textureDir)
        # Descriptive final names can exceed the compositor's Windows path limit
        # once the private directory (and pre-5.0 frame suffix) is included.
        # Render to a compact name, then move it to the unchanged cache filename.
        _, extention = os.path.splitext(textureFilename)
        if hasattr(scene, "compositing_node_group"): # Blender 5.0.0 and higher
            nodes = scene.compositing_node_group.nodes
            fileOutputNode = nodes["File Output"]
            fileOutputNode.directory = self.tmpTextureDir
            fileOutputNode.file_output_items[0].name = 't'
        else: # before Blender 5.0.0
            nodes = scene.node_tree.nodes
            fileOutputNode = nodes["File Output"]
            fileOutputNode.base_path = self.tmpTextureDir
            fileOutputNode.file_slots[0].path = 't'
        if os.name == 'nt':
            frame = '' if hasattr(scene, 'compositing_node_group') else '%04d' % scene.frame_current
            outputPath = os.path.join(self.tmpTextureDir, 't' + frame + '.jpeg')
            if len(os.path.abspath(outputPath)) >= 260:
                raise RuntimeError('Texture render path is too long; choose a shorter data directory: ' + outputPath)
        # Set the correct file format for rendering
        fileOutputNode.format.file_format = _renderFileFormats.get(
            extention.lower(), 'PNG'
        )
        return nodes
    
    def renderTexture(self, scene, textureFilepath):
        from ..app.blender import app
        session = getattr(app, 'osm_session', None)
        if session and session.progressive:
            from .bake_job import BakeQueue
            if self.bakeQueue is None:
                self.bakeQueue = BakeQueue(os.path.dirname(textureFilepath))
            self.bakeQueue.submit(scene, textureFilepath)
            return
        tmpTextureDir = self.tmpTextureDir
        context = 'scene "%s", destination "%s", temporary output "%s"' % (
            scene.name, textureFilepath, tmpTextureDir)
        if os.listdir(tmpTextureDir):
            raise RuntimeError('Texture render directory is not empty: ' + context)
        try:
            result = bpy.ops.render.render(scene=scene.name)
        except Exception as exc:
            raise RuntimeError('Texture rendering failed for %s: %s' % (context, exc)) from exc
        if result != {'FINISHED'}:
            raise RuntimeError('Texture rendering did not finish for ' + context)
        files = os.listdir(tmpTextureDir)
        if len(files) != 1:
            raise RuntimeError('Texture rendering produced %s files; expected exactly one for %s' % (len(files), context))
        outputPath = os.path.join(tmpTextureDir, files[0])
        if not os.path.isfile(outputPath) or not os.path.getsize(outputPath):
            raise RuntimeError('Texture rendering produced no usable image for ' + context)
        os.replace(outputPath, textureFilepath)

    def finish_steps(self):
        if self.bakeQueue:
            yield from self.bakeQueue.steps()
    
    def getTemplateScene(self, sceneName):
        scene = self.templateScenes.get(sceneName)
        if not scene:
            with self.transient.capture() as allocated:
                scene = loadSceneFromFile(self.exportTemplateFilename, sceneName)
            for _, item in allocated:
                item[TRANSIENT] = True
            self.linkedScenes.append(scene.name)
            self.templateScenes[sceneName] = scene
        return scene
    
    def setScaleNode(self, nodes, nodeName, scaleX, scaleY):
        scaleInputs = nodes[nodeName].inputs
        scaleInputs['X'].default_value = scaleX
        scaleInputs['Y'].default_value = scaleY
    
    def setTranslateNode(self, nodes, nodeName, translateX, translateY):
        translateInputs = nodes[nodeName].inputs
        translateInputs['X'].default_value = translateX
        translateInputs['Y'].default_value = translateY
    
    def setImage(self, fileName, path, nodes, nodeName):
        return setImage(
            fileName,
            path,
            nodes,
            nodeName
        )
    
    def setColor(self, color, nodes, nodeName):
        nodes[nodeName].outputs[0].default_value = color
